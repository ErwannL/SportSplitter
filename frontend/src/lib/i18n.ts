export type Lang = "fr" | "en";
export const DICTS: Record<Lang, Record<Key, string>> = { fr, en };

export function translate(lang: Lang, key: Key, params: Params = {}): string {
  return DICTS[lang][key].replace(/\{(\w+)\}/g, (_, k: string) => (k in params ? String(params[k]) : `{${k}}`));
}

/** Traduit un problème ou un écart renvoyé par l'API (repli sur le texte serveur). */
export function translateCode(lang: Lang, code: string, params: Params | undefined, fallback: string): string {
  const key = `issue.${code}` as Key;
  if (!(key in DICTS[lang]) || !params) return fallback;
  const p: Params = { ...params };
  if (typeof p.period === "string" && `period.${p.period}` in DICTS[lang]) {
    p.period = DICTS[lang][`period.${p.period as Period}` as Key];
  }
  return translate(lang, key, p);
}

/** Suggestion de correction pour un problème (code API ou clé « ready.* »). */
export function translateFix(lang: Lang, code: string, params: Params | undefined): string | null {
  const key = `fix.${code}` as Key;
  if (!(key in DICTS[lang])) return null;
  return translate(lang, key, params ?? {});
}

export const segmentKey = (s: Segment) => `segment.${s}` as Key;
export const periodKey = (p: Period) => `period.${p}` as Key;
